-- ============================================================================
-- cleanup-demo-data.sql —— 清除 Flyway 基线自带的演示数据（F-16 定案：选项②）
--
-- 【为什么需要这个脚本】V202608120000__baseline.sql 尾部插了一个「示例教育机构
--   （演示租户）」及其管理员/导师/学员三个账号。基线是冻结的（契约 §7.3），
--   这些行会跟着每一次新环境初始化进去 —— 首次生产部署时它们确实进了生产库。
--   F-16 登记的正是「基线自带示例数据进不进生产」，需方定案：**不进，删掉**。
--
-- 【为什么是物理删除，而不是 deleted_at 软删除】契约 §2.2 的「核心业务数据禁止
--   物理删除」针对的是**真实业务数据**（课程/题目/作业/答卷），理由是可追溯与可恢复。
--   这批行不是业务数据，是**本就不该存在于生产的种子数据**：软删除会把它们永久
--   留在表里，`sys_tenant` 的租户列表、`org_node` 的树查询虽然过滤掉了它们，
--   但 `uk_tenant_phone` / `uk_username` 这类唯一索引仍带着 `deleted_at` 参与判定，
--   将来真有机构用 13800000001 这个号就会撞上一条看不见的历史行。需方定案：物理删。
--
-- 【为什么要进仓库，而不是手敲】下一个环境（测试环境、灾备重建）会遇到一模一样的
--   问题，而那时没人记得是哪几行。基线不能改，所以这个脚本会被反复用到。
--
-- 【幂等】全部 DELETE 都按显式主键，重复执行匹配 0 行、不报错。
--
-- 【执行方式】不进 Flyway。它是**环境治理动作**不是 schema 变更：
--   进 Flyway 就意味着"每个环境都必须删"，而开发/测试环境可能恰恰要留着这批数据。
--       mysql -h<rds> -u<admin> -p <edumatrix> < deploy/prod/cleanup-demo-data.sql
--
-- ============================================================================
-- ⚠⚠ 不可删清单 —— 删掉其中任何一行，系统即不可用。执行前逐条确认 ⚠⚠
-- ============================================================================
--   sys_user       1953827104412590101  superadmin，平台超级管理员，全库唯一的
--                                       可登录账号（node_id = 0，tenant_id = 0）
--   sys_user_role  1953827104412590301  superadmin → super_admin 的角色绑定。
--                                       删了它 /auth/me 的 perms 恒为空数组，
--                                       而接口仍返回 200 —— F-1 那个「不报错故障」
--   org_node       id = 0               平台根哨兵（parent_id = -1、ancestors = ''）。
--                                       整套 ancestors 前缀方案的基础，
--                                       代码里是 NodePath.ROOT_SENTINEL_ID；
--                                       每个机构根节点的 ancestors 都是 '0'，
--                                       删了它全系统的子树判定与租户开通一起塌
--   sys_role       四行内置角色          1953827104412590201 super_admin
--                  （全表保留）          1953827104412590202 org_admin
--                                       1953827104412590203 teacher
--                                       1953827104412590204 student
--                                       它们是 tenant_id = 0 的平台级行，全租户共用
--   sys_menu / sys_role_menu             126 / 206 行菜单与绑定，与演示数据无关
-- ============================================================================

START TRANSACTION;

-- ---------------------------------------------------------------------------
-- ① 档案表（叶子先删：它们通过 node_id / user_id 指向下面要删的节点与账号）
-- ---------------------------------------------------------------------------

-- 演示学员「示例学员」的学籍档案，node_id = …404、user_id = …104，三者同批插入
DELETE FROM `org_student` WHERE `id` = 1953827104412590601;

-- 演示导师「示例导师」的教师档案，node_id = …403、user_id = …103
DELETE FROM `org_teacher` WHERE `id` = 1953827104412590501;

-- ---------------------------------------------------------------------------
-- ② 组织树节点（自底向上：学员 → 导师 → 机构根，避免中间态出现悬挂父引用）
--    【平台根 id = 0 不在此列】见上方不可删清单
-- ---------------------------------------------------------------------------

-- 「示例学员」节点，node_type = 3，parent = …403
DELETE FROM `org_node` WHERE `id` = 1953827104412590404;

-- 「示例导师」节点，node_type = 2，parent = …001
DELETE FROM `org_node` WHERE `id` = 1953827104412590403;

-- 「示例教育机构（演示租户）」的机构根节点，node_type = 1，parent = 0。
-- 契约 §2.1：其 id 恒等于 tenant_id，所以它与下面那条 sys_tenant 是同一个 id
DELETE FROM `org_node` WHERE `id` = 1953827104412590001;

-- ---------------------------------------------------------------------------
-- ③ 角色绑定（先于账号删：它是账号的从属行）
--    【…301 superadmin 的绑定不在此列】见上方不可删清单
-- ---------------------------------------------------------------------------

DELETE FROM `sys_user_role` WHERE `id` = 1953827104412590302;  -- 13800000001 → org_admin
DELETE FROM `sys_user_role` WHERE `id` = 1953827104412590303;  -- 13800000002 → teacher
DELETE FROM `sys_user_role` WHERE `id` = 1953827104412590304;  -- 13800000003 → student

-- ---------------------------------------------------------------------------
-- ④ 演示账号
--    三个账号的口令哈希都是占位串
--    '$2a$10$BCRYPT_PLACEHOLDER_REPLACE_ON_DEPLOY_0000000000000000'，
--    本就登不进来；删除是为了让手机号 13800000001~3 与这三个 id 彻底释放。
--    【…101 superadmin 不在此列】见上方不可删清单
-- ---------------------------------------------------------------------------

DELETE FROM `sys_user` WHERE `id` = 1953827104412590102;  -- 13800000001 演示机构管理员
DELETE FROM `sys_user` WHERE `id` = 1953827104412590103;  -- 13800000002 演示导师
DELETE FROM `sys_user` WHERE `id` = 1953827104412590104;  -- 13800000003 演示学员

-- ---------------------------------------------------------------------------
-- ⑤ 租户本体（最后删：上面所有行的 tenant_id 都指向它）
-- ---------------------------------------------------------------------------

-- 「示例教育机构（演示租户）」，root_node_id = 自身 id（契约 §2.1 四值恒等）
DELETE FROM `sys_tenant` WHERE `id` = 1953827104412590001;

COMMIT;

-- ============================================================================
-- 执行后自检（期望值写在每行末尾；任何一条对不上都要立刻回滚到备份）
-- ============================================================================
SELECT 'sys_tenant'    AS t, COUNT(*) AS cnt, 0 AS expected FROM `sys_tenant`
UNION ALL SELECT 'sys_user',      COUNT(*), 1 FROM `sys_user`
UNION ALL SELECT 'sys_user_role', COUNT(*), 1 FROM `sys_user_role`
UNION ALL SELECT 'org_node',      COUNT(*), 1 FROM `org_node`
UNION ALL SELECT 'org_teacher',   COUNT(*), 0 FROM `org_teacher`
UNION ALL SELECT 'org_student',   COUNT(*), 0 FROM `org_student`
UNION ALL SELECT 'sys_role',      COUNT(*), 4 FROM `sys_role`;

-- 必须只剩 superadmin
SELECT `id`, `username`, `user_type`, `node_id`, `tenant_id` FROM `sys_user`;

-- 必须只剩 id = 0 的平台根（parent_id = -1、ancestors 为空串）
SELECT `id`, `parent_id`, `ancestors`, `node_name`, `node_type` FROM `org_node`;
