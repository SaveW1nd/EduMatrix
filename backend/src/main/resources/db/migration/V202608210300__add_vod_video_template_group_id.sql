-- F-114 · 上传时可选加密（需方 2026-08-21 定案）
--
-- 【为什么要这一列】两个转码模板组并存之后（加密 / 不加密），
-- 「重新发起转码」（接口 33）必须用【这个视频当初用的那一个】。
-- 用当前配置的那个会在同一个视频上叠出第二套流 → GetPlayInfo 返回两路
-- → 「恰好一路」守卫失败，而它报的原因（「模板组配了多档」）与真实原因对不上。
--
-- 【它与 encrypt_type 分工不同，不要合并】
--   template_group_id = 我们【请求】了什么（意图）—— 上传那一刻就确定
--   encrypt_type      = 实际【产出】了什么（观测）—— 转码完成才知道
-- 合成一列的话，转码失败的视频（status=3）就没有可信的重转依据：
-- 那时 encrypt_type 还只是占位值。
--
-- NULL 表示本列上线前建的历史行；重转时回落到当前配置，并在日志里记一行。
ALTER TABLE `vod_video`
  ADD COLUMN `template_group_id` VARCHAR(64) NULL DEFAULT NULL
  COMMENT '上传时请求的转码模板组 ID（意图，非观测）。重新发起转码必须复用它，否则会在同一视频上叠出第二套流'
  AFTER `encrypt_type`;
