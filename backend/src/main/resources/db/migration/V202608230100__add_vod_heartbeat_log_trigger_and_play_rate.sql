-- F-116 · 心跳按 trigger 分流（需方 2026-08-22 定案）—— 补上它落库的地方
--
-- 【为什么必须有 trigger_type 这一列】
-- F-116 定案「取枚举不取布尔」，需方给的理由原话是：
--     「它会落进 vod_heartbeat_log，顺带说明每条心跳是为什么来的；
--       布尔只能答『是不是周期的』，枚举能答『学生当时在干什么』
--       —— 而日志是第一版唯一的行为事实来源。」
-- 而这张表【原来没有这一列】，定案的落地位置清单里也没有它。
-- 不加列的话，那条理由整个落空，而且【不报错】：接口照收 trigger、照它分流，
-- 只是事后一条都查不到 —— 与「枚举退化成布尔」在库里不可区分。
--
-- 【为什么列名不叫 trigger】TRIGGER 是 MySQL 保留字。照本表 current_time_sec
-- 避开 CURRENT_TIME 的先例，加 _type 后缀。请求体字段名不变，仍是 trigger。
--
-- 【为什么存 TINYINT 不存字符串】本表常驻约 0.95 亿行。
-- VARCHAR(8) 存 "resume" 要 7 字节，TINYINT 要 1 字节 —— 差约 570MB。
-- 本表已经为同一个理由拒绝过存 sessionId（CHAR(32) 多占约 3GB，见 02 §4.2.8 权衡说明）。
-- 编码→语义的映射写在本列注释里，与 reject_rule 是同一套办法。
--
-- 【0 = 缺失或非法，不是「默认成 tick」】
-- trigger 缺失或取值非法一律按规则 5 丢弃（F-116 逐字：不得默认成 tick ——
-- 默认成 tick 会让事件心跳重新被卡在 8 秒间隔闸上，等于这条定案没做，而且不报错）。
-- 被丢弃的心跳【明细仍要写本表】，所以必须有一个值表示「它报来的东西不能用」。
-- 用 0 而不是复用 1(tick)：复用就再也分不出「学生在放着」和「客户端根本没报」。
--
-- 【为什么 play_rate 是 DECIMAL(4,2) 而不是 (3,1)】
-- 播放器的常用倍速含 0.75 与 1.25 —— DECIMAL(3,1) 只留一位小数，
-- 会把它们【静默舍成】0.8 / 1.3，而日志的用途正是「回放当时到底发生了什么」。
-- 两位小数是下限，不是余量。
-- 取 4 位总长（±99.99）而不是刚好够用的 3 位（±9.99）：规则 5 判 playRate 越界时
-- 【明细仍写本表，且记的是它报来的真值】。存不下会让 INSERT 直接失败 ——
-- 那是「一条非法心跳把整个请求打挂」，比丢一行日志坏得多。
-- 超出 ±99.99 的极端值写 NULL（reject_rule=5 已经说明它被拒了），故本列可空。
ALTER TABLE `vod_heartbeat_log`
  ADD COLUMN `trigger_type` TINYINT NOT NULL DEFAULT 0
  COMMENT '本条心跳的触发原因（对应请求体 trigger，F-116 新增；TRIGGER 是保留字故加后缀）：0=缺失或取值非法（按规则 5 丢弃，【不得默认成 tick】）1=tick 周期心跳 2=pause 暂停 3=resume 恢复 4=ended 播完 5=leave 离开页面。取枚举不取布尔的理由：布尔只能答「是不是周期的」，枚举能答「学生当时在干什么」，而本表是第一版唯一的行为事实来源。存 TINYINT 不存字符串：常驻 0.95 亿行上 VARCHAR(8) 要多占约 570MB，与本表拒绝存 sessionId 是同一条权衡'
  AFTER `interval_sec`;

ALTER TABLE `vod_heartbeat_log`
  ADD COLUMN `play_rate` DECIMAL(4,2) NULL DEFAULT NULL
  COMMENT '本条心跳上报的倍速（对应请求体 playRate）。【不参与计时】——规则 4：playRate 不得用来调整前端报来的时长，本列只供行为分析。DECIMAL(4,2)：两位小数是下限不是余量（0.75 / 1.25 在 (3,1) 下会被静默舍成 0.8 / 1.3）；总长取 4 位是因为规则 5 判越界时明细仍记真值，存不下会让 INSERT 失败——那是一条非法心跳把整个请求打挂。超出 ±99.99 写 NULL'
  AFTER `trigger_type`;
