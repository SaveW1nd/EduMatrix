-- V202608150000__bind_teacher_org_node_list.sql
-- 模块 06 落地时暴露：teacher 没有 org:node:list，而 03-02 §3.1/§3.2 写着它有
--
-- 【问题】V202608140000 的角色绑定里，菜单 1949000000000100100（org:node:list
--   组织树管理）只绑了 super_admin 与 org_admin：
--       (1949100000000000006, …590201, …100100, 0, …, 'super_admin')
--       (1949100000000000007, …590202, …100100, 0, …, 'org_admin')
--   而同一批数据里 org:node:resetPwd（…100104）是绑了 teacher 的（…000012 行），
--   它的 remark 还写着「teacher 仅限名下学员（03-02 §3.6）」。
--
--   分册这一侧毫无歧义：
--     §3.1 组织树查询 · 权限：org_admin、teacher、super_admin
--     §3.1 数据权限：「教师调用时树根即其教师节点，返回的子树就是名下学员列表」
--     §3.2 节点详情 · 权限：org_admin、teacher、super_admin
--     §2.3 权限总览 · 教师栏：名下学员的查询与维护
--
--   照基线实现，教师调接口 1 与接口 2 会拿 403 ——「重置密码能调、但看不到人」。
--
-- 【为什么改数据而不是在代码里放行】SysUserController 立过的规矩：
--   「收敛不靠代码里的 if，靠菜单绑定数据 —— 权限的真相只有一份。
--     代码里再写一份就有了两份，而两份迟早会分叉。」
--   @SaCheckPermission("org:node:list") 读的就是这张表。
--
-- 【为什么走增量脚本】docs/sql/edumatrix_ddl.sql 是 Flyway 初始基线
--   V202608120000__baseline.sql，契约 §7.3 规定它此后不再改动，
--   一切变更以增量表达，否则新老环境分叉。V202608140000 同理，一个字未动。
--   本文件不改 DDL、不加列、不改索引，只补一行数据。
--
-- 【ID 规则】沿用 V202608140000 的固定值约定（初始化数据必须可重复、可对账，
--   不用雪花算法）。sys_role_menu 的既有 id 段是 1949100000000000001 起的连续序列，
--   末号已用到 …200；本行取 1949100000000000201 续在其后。
--
-- 【tenant_id 必须是 0】契约 §2.9：sys_role_menu 承载平台级行，
--   租户插件对它注入的条件是 (tenant_id = ? OR tenant_id = 0)。
--   写成别的值，这四个内置角色的绑定对所有租户都不可见 —— 表现是 perms 恒为空数组。
--
-- 【幂等】用 INSERT ... SELECT ... WHERE NOT EXISTS 而不是裸 INSERT：
--   Flyway 保证同一版本只执行一次，但开发库常有人手工补过这一行，
--   撞主键会让整个迁移失败、后续版本全部卡住。
-- ============================================================================

INSERT INTO `sys_role_menu` (`id`, `role_id`, `menu_id`, `tenant_id`, `create_by`, `remark`)
SELECT 1949100000000000201, 1953827104412590203, 1949000000000100100, 0,
       1953827104412590101, 'teacher（03-02 §3.1/§3.2：教师可查组织树与节点详情，树根即其教师节点）'
  FROM DUAL
 WHERE NOT EXISTS (
     SELECT 1 FROM `sys_role_menu`
      WHERE `role_id` = 1953827104412590203
        AND `menu_id` = 1949000000000100100
        AND `deleted_at` = 0
 );
