-- F-113 · 断点续播起点由「最远触达」改为「上次离开」（需方 2026-08-21 定案）
--
-- 【为什么要这一列】原设计拿 max_position 当续播起点。放开拖动之后（规则 3 已废止）
-- 那可能只是学生随手拖到过的位置 —— 从那里续播会【跳过他实际没看的中间部分】。
-- PRD F2-8 的验收逐字写着这个场景：拖到 500 秒看一眼又拖回 210 秒然后离开
-- （max_position=500、last_position=210），再次进入应当从 210 秒续播，不是 500 秒。
--
-- 【两列分工不同，不要合并、也不要互相赋值】
--   max_position  = 历史【最远触达】，取大不回退 —— 识别「看到多深」（PRD F2-5 规则 2）
--   last_position = 【上次离开】位置，直写不取大 —— 断点续播起点（PRD F2-8 规则 1）
-- 判读示例：时长 60 分钟 + max_position 10 分钟 = 反复看开头；+ 58 分钟 = 正常看完。
--
-- 【类型必须与 max_position 同为 INT，不得用 DECIMAL】
-- 两列都表示「视频里的某个位置」。精度不同会让「上次离开的位置是不是就是最远位置」
-- 这类判断【永远为假】—— 210 与 210.0 比不相等，而这不会报错，只会让判断静默失灵。
--
-- 【它必须有一个出口，否则这一列等于没建】
-- 本列的唯一出口是接口 31 `GET /api/v1/vod/progress` 的响应字段 lastPosition
-- （PRD F2-8 规则 1 逐字：「调用【进度查询接口】」）。
-- 接口 28 play-auth 回的是 maxPosition，那【不是】续播起点 —— 两个字段都在、
-- 都是「视频里的某个位置」、拿错了不报错，只是学生从没看过的地方开始播。
ALTER TABLE `vod_watch_progress`
  ADD COLUMN `last_position` INT NOT NULL DEFAULT 0
  COMMENT '上次离开位置（秒，断点续播起点）。直写不取大，与 max_position（历史最远触达）分工不同，不要互相赋值'
  AFTER `max_position`;
