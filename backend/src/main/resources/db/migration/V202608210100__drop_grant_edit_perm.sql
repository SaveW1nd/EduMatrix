-- ============================================================================
-- 需方 2026-08-21 定案：删掉孤儿权限 org:grant:edit（F-104）
--
-- 需方原话：「没人用的权限 直接删掉」。
--
-- 【它为什么成了孤儿】03-02 接口 40「修改授权有效期」已随「授权一律永久有效」
--   删除（F-103），而菜单行与两条角色绑定还留在初始化数据里 ——
--   按钮在、端点没了。安全上无风险（没有端点可打，@SaCheckPermission 无从触发），
--   可见的代价是管理端 A12 页面上一个点了没反应的按钮。
--
-- 【三行，不是一行】这条权限绑给了【两个】角色：
--   sys_menu       1949000000000300103   修改授权有效期 / org:grant:edit
--   sys_role_menu  1949100000000000102 → org_admin
--   sys_role_menu  1949100000000000103 → teacher       ← 教师原本也能改有效期，一并没了
--
-- 【两半都要做，只做一半是另一种坏】
--   只删菜单不删绑定 → sys_role_menu 里留下指向不存在菜单的【孤儿绑定行】
--     （SystemMenuIT 早就点过这个形态：它不报错）；
--   只删绑定不删菜单 → 菜单树上仍挂着一个谁都点不到的按钮，
--     且 org:grant:edit 仍占着 uk_perms，将来重用这个标识会撞唯一键。
--   FlywayBaselineIT#menuAndRoleMenuInitialized 的三个数各钉一半：
--     菜单 126 → 125、绑定 202 → 200、DISTINCT perms 119 → 118。
--
-- 【新增增量迁移，绝不改 V202608140000】照 F-72（V202608200000）与
--   V202608210000 的先例：改已应用过的迁移会变校验和，结果是【启动失败】
--   而不是一条干净的红。
--
-- 【父菜单不受影响】1949000000000300100「资源下发中心」还有
--   300101 授权、300102 撤销两个子项，删完不会留下空目录。已核。
--
-- 【顺序：先绑定后菜单】反过来也能跑（无外键），但先删绑定意味着
--   任何一步失败都不会留下「菜单没了、绑定还在」的孤儿行。
--
-- 【可重复执行】：按主键精确删，删过再跑影响 0 行。
-- ============================================================================

DELETE FROM `sys_role_menu`
 WHERE `menu_id` = 1949000000000300103;   -- org_admin(…102) 与 teacher(…103) 两行

DELETE FROM `sys_menu`
 WHERE `id` = 1949000000000300103;        -- org:grant:edit  修改授权有效期
