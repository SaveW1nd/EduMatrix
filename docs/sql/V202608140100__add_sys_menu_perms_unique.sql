-- V202608140100__add_sys_menu_perms_unique.sql
-- 待决项 F-12 的落地：给 sys_menu.perms 加唯一索引
--
-- 【为什么需要】03-01 §4.2 明写 perms「全局唯一」，但基线 edumatrix_ddl.sql 的
--   sys_menu 只有 PRIMARY KEY (id) 与 KEY idx_parent_id (parent_id, sort)。
--   唯一性此前只靠 V202608140000 生成脚本一次性保证，**数据库拦不住手工加行**——
--   两个菜单挂同一个 perms 时，谁的角色绑定生效取决于查询顺序，是静默故障。
--
-- 【为什么走增量脚本】edumatrix_ddl.sql 是 Flyway 初始基线 V202608120000__baseline.sql，
--   契约 §7.3 规定该文件此后不再改动，一切变更以增量表达，否则新老环境分叉。
--
-- 【为什么末尾追加 deleted_at】契约 §2.2 的统一约定：逻辑删除用毫秒时间戳而非 0/1，
--   唯一索引末尾一律追加该列——否则同一个 perms「删了又建」，第二次就会撞唯一键。
--
-- 【为什么不必为目录行做特殊处理】perms 可空（VARCHAR(100) NULL），
--   而 MySQL 的唯一索引不约束 NULL：当前 124 行菜单中有 7 行 M 目录的 perms IS NULL，
--   它们天然不参与唯一冲突，无需另置默认值或排除条件。
--
-- 【耗时】sys_menu 为百行量级的平台级小表，ALGORITHM=INPLACE 瞬时完成，
--   不适用契约 §7.3 的大表在线 DDL 约定。
-- ============================================================================

ALTER TABLE `sys_menu` ADD UNIQUE KEY `uk_perms` (`perms`, `deleted_at`);
